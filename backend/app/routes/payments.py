from __future__ import annotations

from typing import Any

from fastapi import APIRouter, Depends, HTTPException, Request
from pydantic import ValidationError
from starlette.datastructures import UploadFile as StarletteUploadFile

from app.auth import get_current_user
from app.models.schemas import (
    PaymentCreate,
    PaymentProofError,
    PaymentProofErrorCode,
    PaymentProofErrorStage,
    PaymentProofUpload,
)
from app.services import payment_service
from app.utils.http_errors import raise_as_http

router = APIRouter(prefix="/api/payments", tags=["payments"], dependencies=[Depends(get_current_user)])

# This key is deliberately private to the existing payment service boundary.
# The service consumes the bytes and metadata after the payment row exists and
# generates the final payment-scoped attachment reference itself.
_INTERNAL_PROOF_UPLOAD_KEY = "_proof_upload"

# Proof metadata is response-only.  A client may upload one file, but it may
# not choose the persisted reference or submit a fabricated metadata object.
_CLIENT_PROOF_METADATA_KEYS = frozenset(
    {
        "proof",
        "paymentProof",
        "payment_proof",
        "fileName",
        "file_name",
        "mimeType",
        "mime_type",
        "sizeBytes",
        "size_bytes",
        "uploadedAt",
        "uploaded_at",
        "attachmentReference",
        "attachment_reference",
        "proof_fileName",
        "proof_file_name",
        "proof_mimeType",
        "proof_mime_type",
        "proof_sizeBytes",
        "proof_size_bytes",
        "proof_uploadedAt",
        "proof_uploaded_at",
        "proof_attachmentReference",
        "proof_attachment_reference",
    }
)


def _validation_detail(error: ValidationError) -> dict[str, Any]:
    errors: dict[str, str] = {}
    for item in error.errors():
        location = [str(part) for part in item.get("loc", ()) if part != "body"]
        field = location[-1] if location else "payment"
        errors[field] = str(item.get("msg", "Invalid value"))
    return {"message": "Validation failed", "errors": errors}


def _reject_client_proof_metadata(payload: dict[str, Any]) -> None:
    supplied = sorted(key for key in payload if key in _CLIENT_PROOF_METADATA_KEYS)
    if not supplied:
        return

    message = (
        "Payment proof metadata and attachment references are generated by the backend; "
        "upload one file in the proof field instead."
    )
    proof_error = PaymentProofError(
        code=PaymentProofErrorCode.proof_invalid,
        stage=PaymentProofErrorStage.write,
        message=message,
        paymentId=str(payload.get("id") or "unassigned"),
        retryable=False,
    ).model_dump(mode="json")
    raise HTTPException(
        status_code=422,
        detail={
            "message": message,
            "errors": {key: "This proof field is server-managed." for key in supplied},
            "proofError": proof_error,
        },
    )


def _validate_payment_payload(payload: dict[str, Any]) -> None:
    _reject_client_proof_metadata(payload)
    try:
        PaymentCreate.model_validate(payload)
    except ValidationError as exc:
        raise HTTPException(status_code=422, detail=_validation_detail(exc)) from exc


async def _parse_payment_request(request: Request) -> tuple[dict[str, Any], PaymentProofUpload | None]:
    content_type = request.headers.get("content-type", "").split(";", 1)[0].strip().lower()

    if content_type == "multipart/form-data":
        try:
            form = await request.form()
        except Exception as exc:
            raise HTTPException(
                status_code=422,
                detail={"message": "Invalid multipart payment request."},
            ) from exc

        payload: dict[str, Any] = {}
        file_entries: list[tuple[str, StarletteUploadFile]] = []
        for key, value in form.multi_items():
            if isinstance(value, StarletteUploadFile):
                file_entries.append((key, value))
                continue
            if key == "proof":
                raise HTTPException(
                    status_code=422,
                    detail={"message": "The proof field must contain one uploaded file."},
                )
            if key in payload:
                raise HTTPException(
                    status_code=422,
                    detail={"message": f"Payment field {key!r} was submitted more than once."},
                )
            payload[key] = value

        if file_entries and (len(file_entries) != 1 or file_entries[0][0] != "proof"):
            _reject_client_proof_metadata({**payload, "proof": "multiple or unexpected files"})

        _validate_payment_payload(payload)
        normalized_payload = PaymentCreate.model_validate(payload).model_dump(
            exclude_unset=True,
            mode="json",
        )

        if not file_entries:
            return normalized_payload, None

        uploaded_file = file_entries[0][1]
        try:
            content = await uploaded_file.read()
            proof_upload = PaymentProofUpload(
                fileName=uploaded_file.filename or "",
                mimeType=uploaded_file.content_type or "application/octet-stream",
                sizeBytes=len(content),
                content=content,
            )
        except ValidationError as exc:
            message = "The uploaded payment proof has invalid metadata."
            raise HTTPException(
                status_code=422,
                detail={
                    "message": message,
                    "proofError": PaymentProofError(
                        code=PaymentProofErrorCode.proof_invalid,
                        stage=PaymentProofErrorStage.write,
                        message=message,
                        paymentId=str(payload.get("id") or "unassigned"),
                        retryable=False,
                    ).model_dump(mode="json"),
                    "errors": _validation_detail(exc)["errors"],
                },
            ) from exc
        finally:
            await uploaded_file.close()

        return normalized_payload, proof_upload

    try:
        payload = await request.json()
    except Exception as exc:
        raise HTTPException(
            status_code=400,
            detail="Payment requests must be JSON or multipart form data.",
        ) from exc
    if not isinstance(payload, dict):
        raise HTTPException(status_code=422, detail={"message": "Payment payload must be an object."})

    _validate_payment_payload(payload)
    # Preserve the ordinary JSON service contract and its existing response
    # shape; validation above is only the request-boundary guard.
    return payload, None


@router.get("")
def list_payments(invoiceId: str | None = None) -> list[dict]:
    try:
        if invoiceId:
            return payment_service.list_payments_for_invoice(invoiceId)
        return payment_service.list_payments()
    except Exception as exc:
        raise_as_http(exc)


@router.get("/{payment_id}")
def get_payment(payment_id: str) -> dict:
    try:
        return payment_service.get_payment(payment_id)
    except Exception as exc:
        raise_as_http(exc)


@router.post("", status_code=201)
async def record_payment(request: Request) -> dict:
    try:
        payload, proof_upload = await _parse_payment_request(request)
        if proof_upload is not None:
            # Do not put this through PaymentCreate: it is an internal,
            # request-scoped upload value, not client payment metadata.  The
            # payment service must generate the attachment reference after it
            # has allocated and persisted the payment identity.
            payload[_INTERNAL_PROOF_UPLOAD_KEY] = proof_upload.model_dump(mode="python")
        result = payment_service.record_payment(payload)
        # A proof failure happens after the payment row and activity are
        # durable. Return the retained-payment envelope as a structured 422
        # so apiDataProvider can preserve the payment instead of treating it
        # as an unknown persistence failure. Ordinary no-proof responses keep
        # the existing raw-payment shape.
        if isinstance(result, dict) and result.get("proofError") is not None:
            raise HTTPException(status_code=422, detail=result)
        return result
    except HTTPException:
        raise
    except Exception as exc:
        raise_as_http(exc)


@router.put("/{payment_id}")
def update_payment(payment_id: str, payload: dict) -> dict:
    # Payments are treated as append-only financial records; editing is
    # intentionally unsupported - delete and re-record instead. Route kept
    # for API completeness per spec item 21, but reports why it declines.
    raise HTTPException(
        status_code=405,
        detail="Payments cannot be edited once recorded. Delete this payment and record a new one instead.",
    )


@router.delete("/{payment_id}", status_code=200)
def delete_payment(payment_id: str) -> dict:
    try:
        payment_service.delete_payment(payment_id)
        return {"deleted": True, "id": payment_id}
    except Exception as exc:
        raise_as_http(exc)
