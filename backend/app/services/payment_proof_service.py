"""Safe application-managed storage for one payment proof attachment.

The workbook remains the source of payment metadata.  This module owns only
binary attachment bytes and the opaque, payment-scoped reference that points
to them.  It deliberately does not expose filesystem paths in its public
metadata, errors, or cleanup diagnostics.

Payment-service orchestration can use the staged API when it needs to update
the workbook after readback validation::

    staged = store.stage_upload(payment_id, upload)
    store.promote(staged)
    store.validate_readback(staged)
    # enrich the matching workbook row here
    cleanup = store.cleanup_reference(previous_reference, payment_id=payment_id)

``replace`` is provided for callers that want the ordering enforced around an
injected metadata-enrichment callback.  A prior reference is cleaned only
after the new attachment has been promoted, read back, and enriched.
"""
from __future__ import annotations

import hashlib
import os
import re
import secrets
import tempfile
from dataclasses import dataclass, field
from pathlib import Path, PurePosixPath, PureWindowsPath
from typing import Any, BinaryIO, Callable, Mapping

from app.excel.workbook import BASE_DIR, DATA_DIR
from app.utils.validators import now_iso

# The first variable is the documented configuration knob.  The aliases make
# the service usable from existing local deployments without requiring a new
# configuration package or a second persistence system.
ATTACHMENT_ROOT_ENV = "SFT_BILLING_ATTACHMENT_ROOT"
_ATTACHMENT_ROOT_ENV_ALIASES = (
    ATTACHMENT_ROOT_ENV,
    "SFT_BILLING_PAYMENT_PROOF_ROOT",
    "PAYMENT_PROOF_ATTACHMENT_ROOT",
    "PAYMENT_PROOF_ROOT",
)
DEFAULT_ATTACHMENT_DIRECTORY = "payment-proofs"

_PAYMENT_ID_PATTERN = re.compile(r"^[A-Za-z0-9][A-Za-z0-9._-]{0,127}$")
_REFERENCE_TOKEN_PATTERN = re.compile(r"^[a-f0-9]{32}$")
_ALLOWED_PROOF_EXTENSIONS = frozenset({".png", ".jpg", ".jpeg", ".pdf"})
_ALLOWED_PROOF_MIME_TYPES = frozenset({"image/png", "image/jpeg", "image/jpg", "application/pdf"})


class AttachmentServiceError(RuntimeError):
    """Base error with safe machine-readable stage/category information."""

    def __init__(
        self,
        message: str,
        *,
        category: str,
        stage: str,
        retryable: bool = False,
        cleanup_diagnostic_category: str | None = None,
    ) -> None:
        # Messages are fixed, path-free strings.  Do not pass an underlying OS
        # exception or a user-supplied filename into this constructor.
        super().__init__(message)
        self.category = category
        self.stage = stage
        self.retryable = retryable
        self.cleanup_diagnostic_category = cleanup_diagnostic_category


class AttachmentValidationError(AttachmentServiceError):
    """The upload metadata or content is not acceptable."""


class AttachmentSecurityError(AttachmentServiceError):
    """A configured root or reference violates the storage safety boundary."""


class AttachmentWriteError(AttachmentServiceError):
    """The staged or promoted attachment could not be written."""


class AttachmentReadbackError(AttachmentServiceError):
    """The stored attachment could not be read back or did not match."""


class AttachmentEnrichmentError(AttachmentServiceError):
    """The caller could not commit proof metadata after attachment write."""


@dataclass(frozen=True)
class AttachmentUpload:
    """Input-only upload value accepted by the storage service.

    ``file_name`` and ``mime_type`` are retained as display metadata only.
    The filesystem name is always generated by this service.  ``content`` may
    be bytes or a synchronous binary stream such as ``UploadFile.file``.
    """

    file_name: str
    mime_type: str
    content: bytes | bytearray | memoryview | BinaryIO
    size_bytes: int | None = None

    @classmethod
    def from_mapping(cls, value: Mapping[str, Any]) -> "AttachmentUpload":
        """Build an upload from either Python or API-style field names."""
        content = value.get("content", value.get("file"))
        file_name = value.get("file_name", value.get("fileName"))
        mime_type = value.get("mime_type", value.get("mimeType"))
        size_bytes = value.get("size_bytes", value.get("sizeBytes"))
        return cls(
            file_name=file_name,
            mime_type=mime_type,
            content=content,
            size_bytes=size_bytes,
        )


@dataclass(frozen=True)
class PaymentProofMetadata:
    """Persistable proof metadata; it contains no server filesystem path."""

    file_name: str
    mime_type: str
    size_bytes: int
    uploaded_at: str
    attachment_reference: str

    def to_dict(self) -> dict[str, Any]:
        """Return the camelCase shape used by workbook/API payment rows."""
        return {
            "fileName": self.file_name,
            "mimeType": self.mime_type,
            "sizeBytes": self.size_bytes,
            "uploadedAt": self.uploaded_at,
            "attachmentReference": self.attachment_reference,
        }

    # The alias makes the object convenient at the DataProvider boundary.
    as_dict = to_dict


@dataclass(frozen=True)
class CleanupResult:
    """Safe result for best-effort cleanup.

    ``diagnostic_category`` is intentionally the only failure detail.  It is
    safe to log or return internally and never contains a path or exception
    text.
    """

    success: bool
    diagnostic_category: str | None = None


@dataclass
class StagedAttachment:
    """A private staged attachment handle used until metadata is enriched."""

    payment_id: str
    metadata: PaymentProofMetadata
    _service: "PaymentProofAttachmentService" = field(repr=False)
    _temporary_path: Path = field(repr=False)
    _final_path: Path = field(repr=False)
    _content_sha256: str = field(repr=False)
    _content_size: int = field(repr=False)
    _promoted: bool = field(default=False, repr=False)

    @property
    def reference(self) -> str:
        return self.metadata.attachment_reference

    @property
    def promoted(self) -> bool:
        return self._promoted

    def promote(self) -> PaymentProofMetadata:
        return self._service.promote(self)

    def validate_readback(self) -> bytes:
        return self._service.validate_readback(self)

    def cleanup(self) -> CleanupResult:
        return self._service.cleanup(self)


@dataclass(frozen=True)
class ReplacementResult:
    """Result of a successful new proof plus best-effort prior-file cleanup."""

    metadata: PaymentProofMetadata
    prior_cleanup: CleanupResult


MetadataEnricher = Callable[[dict[str, Any]], Any]


def resolve_attachment_root(configured_root: str | os.PathLike[str] | None = None) -> Path:
    """Resolve the configured attachment root or the backend data fallback.

    Relative configured values are rooted at the backend directory rather
    than the process working directory.  The returned path is normalized but
    is not created until a ``PaymentProofAttachmentService`` is constructed.
    """

    raw_value: str | os.PathLike[str] | None = configured_root
    if raw_value is None:
        for environment_name in _ATTACHMENT_ROOT_ENV_ALIASES:
            value = os.environ.get(environment_name)
            if value and value.strip():
                raw_value = value.strip()
                break

    if raw_value is None:
        raw_path = DATA_DIR / DEFAULT_ATTACHMENT_DIRECTORY
    else:
        raw_path = Path(raw_value).expanduser()
        if not raw_path.is_absolute():
            raw_path = BASE_DIR / raw_path

    # abspath normalizes lexical '..' without following symlinks; the service
    # performs the symlink checks before resolving this path canonically.
    return Path(os.path.abspath(os.fspath(raw_path)))


class PaymentProofAttachmentService:
    """Store one generated, payment-scoped proof file at a time.

    The ``attachment_root`` argument is intended for deployment configuration
    and tests.  When omitted, the service uses the configured environment
    root, then ``backend/data/payment-proofs``.
    """

    def __init__(
        self,
        attachment_root: str | os.PathLike[str] | None = None,
        *,
        max_size_bytes: int | None = None,
        clock: Callable[[], str] = now_iso,
    ) -> None:
        if max_size_bytes is not None and (
            isinstance(max_size_bytes, bool)
            or not isinstance(max_size_bytes, int)
            or max_size_bytes < 0
        ):
            raise ValueError("max_size_bytes must be a non-negative integer")

        raw_root = resolve_attachment_root(attachment_root)
        self._root = self._normalize_root(raw_root)
        self._max_size_bytes = max_size_bytes
        self._clock = clock
        self._ensure_root()

    def stage_upload(
        self,
        payment_id: str,
        upload: AttachmentUpload | Mapping[str, Any] | Any,
    ) -> StagedAttachment:
        """Write bytes to a generated temporary file under the payment folder."""

        safe_payment_id = self._validate_payment_id(payment_id)
        normalized_upload = self._coerce_upload(upload)
        content = self._read_upload_content(normalized_upload.content)
        metadata = self._build_metadata(safe_payment_id, normalized_upload, content)
        final_path = self._path_for_reference(
            metadata.attachment_reference,
            expected_payment_id=safe_payment_id,
            must_exist=False,
        )
        payment_dir = final_path.parent
        self._ensure_payment_directory(payment_dir, safe_payment_id)

        temporary_path: Path | None = None
        try:
            file_descriptor, temporary_name = tempfile.mkstemp(
                prefix=".payment-proof-",
                dir=os.fspath(payment_dir),
            )
            temporary_path = Path(temporary_name)
            self._assert_safe_internal_path(temporary_path, safe_payment_id)
            with os.fdopen(file_descriptor, "wb") as temporary_file:
                temporary_file.write(content)
                temporary_file.flush()
                os.fsync(temporary_file.fileno())
        except AttachmentServiceError:
            if temporary_path is not None:
                self._unlink_staged_path(temporary_path)
            raise
        except (OSError, ValueError):
            if temporary_path is not None:
                self._unlink_staged_path(temporary_path)
            raise AttachmentWriteError(
                "Could not stage payment proof.",
                category="write_failed",
                stage="write",
                retryable=True,
            ) from None

        return StagedAttachment(
            payment_id=safe_payment_id,
            metadata=metadata,
            _service=self,
            _temporary_path=temporary_path,
            _final_path=final_path,
            _content_sha256=hashlib.sha256(content).hexdigest(),
            _content_size=len(content),
        )

    def promote(self, staged: StagedAttachment) -> PaymentProofMetadata:
        """Atomically promote a staged file to its generated final reference."""

        self._assert_owned_staged_attachment(staged)
        if staged._promoted:
            return staged.metadata

        self._assert_safe_internal_path(staged._temporary_path, staged.payment_id)
        self._path_for_reference(
            staged.reference,
            expected_payment_id=staged.payment_id,
            must_exist=False,
        )
        if staged._final_path.exists() or staged._final_path.is_symlink():
            raise AttachmentWriteError(
                "Generated payment proof reference is already in use.",
                category="reference_collision",
                stage="write",
                retryable=True,
            )

        try:
            os.replace(staged._temporary_path, staged._final_path)
            # Mark the handle promoted immediately after the atomic rename so
            # any subsequent validation failure can clean the final orphan.
            staged._promoted = True
            self._assert_safe_internal_path(staged._final_path, staged.payment_id)
            if not staged._final_path.is_file():
                raise OSError("promoted target is not a regular file")
        except AttachmentServiceError:
            raise
        except (OSError, ValueError):
            raise AttachmentWriteError(
                "Could not promote payment proof.",
                category="promote_failed",
                stage="write",
                retryable=True,
            ) from None

        return staged.metadata

    def validate_readback(self, staged: StagedAttachment) -> bytes:
        """Read a staged/promoted file and verify size and content digest."""

        self._assert_owned_staged_attachment(staged)
        path = staged._final_path if staged._promoted else staged._temporary_path
        try:
            content = self._read_safe_path(path, staged.payment_id)
        except AttachmentServiceError as exc:
            raise AttachmentReadbackError(
                "Payment proof readback failed.",
                category="readback_failed",
                stage="readback",
                retryable=True,
            ) from exc

        if len(content) != staged._content_size or hashlib.sha256(content).hexdigest() != staged._content_sha256:
            raise AttachmentReadbackError(
                "Payment proof readback did not match the staged content.",
                category="content_mismatch",
                stage="readback",
                retryable=True,
            )
        return content

    # Short alias for callers that use the terminology from the design.
    readback = validate_readback

    def save(
        self,
        payment_id: str,
        upload: AttachmentUpload | Mapping[str, Any] | Any,
    ) -> PaymentProofMetadata:
        """Stage, promote, and read back a new proof attachment."""

        staged = self.stage_upload(payment_id, upload)
        try:
            metadata = self.promote(staged)
            self.validate_readback(staged)
            return metadata
        except AttachmentServiceError as exc:
            cleanup = self.cleanup(staged)
            if not cleanup.success:
                exc.cleanup_diagnostic_category = cleanup.diagnostic_category
            raise
        except Exception:
            self.cleanup(staged)
            raise AttachmentReadbackError(
                "Payment proof readback failed.",
                category="readback_failed",
                stage="readback",
                retryable=True,
            ) from None

    # Descriptive aliases keep the service usable at the payment boundary.
    store = save
    save_payment_proof = save

    def replace(
        self,
        payment_id: str,
        upload: AttachmentUpload | Mapping[str, Any] | Any,
        *,
        prior_reference: str | None = None,
        metadata_enricher: MetadataEnricher | None = None,
    ) -> ReplacementResult:
        """Commit a new proof before attempting prior-file cleanup.

        ``metadata_enricher`` is an injected callback owned by the payment
        service.  It receives only persisted metadata (never a path).  If it
        fails, the new file is cleaned best-effort and the prior reference is
        left untouched.
        """

        safe_payment_id = self._validate_payment_id(payment_id)
        if prior_reference is not None:
            # Validate the prior reference before writing anything.  It may be
            # absent on disk because an older proof is unavailable; that is not
            # a reason to risk writing outside the managed root.
            self._path_for_reference(
                prior_reference,
                expected_payment_id=safe_payment_id,
                must_exist=False,
            )

        staged = self.stage_upload(safe_payment_id, upload)
        try:
            metadata = self.promote(staged)
            self.validate_readback(staged)

            if metadata_enricher is not None:
                try:
                    metadata_enricher(metadata.to_dict())
                except Exception:
                    cleanup = self.cleanup(staged)
                    raise AttachmentEnrichmentError(
                        "Payment proof metadata could not be enriched.",
                        category="metadata_enrichment_failed",
                        stage="metadata_enrichment",
                        retryable=True,
                        cleanup_diagnostic_category=(
                            cleanup.diagnostic_category if not cleanup.success else None
                        ),
                    ) from None

            prior_cleanup = CleanupResult(success=True)
            if prior_reference is not None and prior_reference != metadata.attachment_reference:
                # Cleanup is deliberately last and best effort.  A cleanup
                # failure does not undo the newly enriched current proof.
                prior_cleanup = self.cleanup_reference(
                    prior_reference,
                    payment_id=safe_payment_id,
                )
            return ReplacementResult(metadata=metadata, prior_cleanup=prior_cleanup)
        except AttachmentServiceError as exc:
            # An enrichment failure already cleaned the new file; cleanup is
            # idempotent and also handles readback/promote failures.
            cleanup = self.cleanup(staged)
            if not cleanup.success and exc.cleanup_diagnostic_category is None:
                exc.cleanup_diagnostic_category = cleanup.diagnostic_category
            raise
        except Exception:
            self.cleanup(staged)
            raise AttachmentReadbackError(
                "Payment proof readback failed.",
                category="readback_failed",
                stage="readback",
                retryable=True,
            ) from None

    def read(self, reference: str, *, payment_id: str | None = None) -> bytes:
        """Read only a normalized, managed reference within the attachment root."""

        safe_payment_id = self._validate_payment_id(payment_id) if payment_id is not None else None
        try:
            path = self._path_for_reference(
                reference,
                expected_payment_id=safe_payment_id,
                must_exist=True,
            )
            return self._read_safe_path(path, safe_payment_id or self._reference_payment_id(reference))
        except AttachmentSecurityError:
            raise
        except AttachmentServiceError:
            raise AttachmentReadbackError(
                "Payment proof is unavailable.",
                category="unavailable",
                stage="readback",
                retryable=True,
            ) from None

    def validate_reference(
        self,
        reference: str,
        *,
        payment_id: str | None = None,
        require_exists: bool = False,
    ) -> str:
        """Validate a reference and return the same opaque value, never a path."""

        safe_payment_id = self._validate_payment_id(payment_id) if payment_id is not None else None
        self._path_for_reference(
            reference,
            expected_payment_id=safe_payment_id,
            must_exist=require_exists,
        )
        return reference

    def cleanup_reference(
        self,
        reference: str,
        *,
        payment_id: str | None = None,
    ) -> CleanupResult:
        """Best-effort remove of one managed reference with safe diagnostics."""

        try:
            safe_payment_id = self._validate_payment_id(payment_id) if payment_id is not None else None
            path = self._path_for_reference(
                reference,
                expected_payment_id=safe_payment_id,
                must_exist=False,
            )
        except AttachmentSecurityError as exc:
            return CleanupResult(False, self._safe_cleanup_category(exc.category))
        except AttachmentServiceError as exc:
            return CleanupResult(False, self._safe_cleanup_category(exc.category))

        return self._unlink_managed_path(path, safe_payment_id or self._reference_payment_id(reference))

    # Alias used by callers describing these as orphan files.
    cleanup_orphan = cleanup_reference

    def cleanup(self, staged: StagedAttachment) -> CleanupResult:
        """Best-effort cleanup of a staged file or its promoted final file."""

        try:
            self._assert_owned_staged_attachment(staged)
        except AttachmentServiceError as exc:
            return CleanupResult(False, self._safe_cleanup_category(exc.category))

        result = CleanupResult(success=True)
        if staged._promoted:
            result = self._unlink_managed_path(staged._final_path, staged.payment_id)
        else:
            result = self._unlink_staged_path(staged._temporary_path)
        return result

    def _build_metadata(
        self,
        payment_id: str,
        upload: AttachmentUpload,
        content: bytes,
    ) -> PaymentProofMetadata:
        file_name = self._display_file_name(upload.file_name)
        mime_type = self._display_mime_type(upload.mime_type)
        extension = Path(file_name).suffix.lower()
        if extension not in _ALLOWED_PROOF_EXTENSIONS or (
            mime_type not in _ALLOWED_PROOF_MIME_TYPES
            and mime_type != "application/octet-stream"
        ):
            raise AttachmentValidationError(
                "Payment proof must be a PNG, JPG, JPEG, or PDF file.",
                category="unsupported_file_type",
                stage="write",
                retryable=False,
            )
        actual_size = len(content)
        if upload.size_bytes is not None:
            if isinstance(upload.size_bytes, bool) or not isinstance(upload.size_bytes, int) or upload.size_bytes < 0:
                raise AttachmentValidationError(
                    "Payment proof metadata is invalid.",
                    category="invalid_size",
                    stage="write",
                    retryable=False,
                )
            if upload.size_bytes != actual_size:
                raise AttachmentValidationError(
                    "Payment proof size does not match its content.",
                    category="size_mismatch",
                    stage="write",
                    retryable=False,
                )
        if self._max_size_bytes is not None and actual_size > self._max_size_bytes:
            raise AttachmentValidationError(
                "Payment proof exceeds the configured size limit.",
                category="size_exceeded",
                stage="write",
                retryable=False,
            )

        token = secrets.token_hex(16)
        reference = f"{payment_id}/{token}"
        return PaymentProofMetadata(
            file_name=file_name,
            mime_type=mime_type,
            size_bytes=actual_size,
            uploaded_at=str(self._clock()),
            attachment_reference=reference,
        )

    @staticmethod
    def _coerce_upload(upload: AttachmentUpload | Mapping[str, Any] | Any) -> AttachmentUpload:
        if isinstance(upload, AttachmentUpload):
            return upload
        if isinstance(upload, Mapping):
            try:
                return AttachmentUpload.from_mapping(upload)
            except (AttributeError, TypeError):
                pass
        # Accept FastAPI UploadFile-like values without importing FastAPI into
        # this storage layer.  Its filename/content_type/file fields are only
        # metadata/input; no user filename is used for a filesystem path.
        if hasattr(upload, "filename") and hasattr(upload, "file"):
            return AttachmentUpload(
                file_name=getattr(upload, "filename"),
                mime_type=getattr(upload, "content_type", None),
                content=getattr(upload, "file"),
                size_bytes=getattr(upload, "size", None),
            )
        raise AttachmentValidationError(
            "Payment proof upload is invalid.",
            category="invalid_upload",
            stage="write",
            retryable=False,
        )

    @staticmethod
    def _read_upload_content(content: Any) -> bytes:
        if isinstance(content, bytes):
            return content
        if isinstance(content, (bytearray, memoryview)):
            return bytes(content)
        if hasattr(content, "read"):
            try:
                value = content.read()
            except (OSError, ValueError):
                raise AttachmentValidationError(
                    "Payment proof content could not be read.",
                    category="unreadable_upload",
                    stage="write",
                    retryable=True,
                ) from None
            if not isinstance(value, (bytes, bytearray, memoryview)):
                raise AttachmentValidationError(
                    "Payment proof content is not binary.",
                    category="non_binary_upload",
                    stage="write",
                    retryable=False,
                )
            return bytes(value)
        raise AttachmentValidationError(
            "Payment proof content is invalid.",
            category="invalid_content",
            stage="write",
            retryable=False,
        )

    @staticmethod
    def _display_file_name(value: Any) -> str:
        if not isinstance(value, str) or "\x00" in value:
            raise AttachmentValidationError(
                "Payment proof filename is invalid.",
                category="invalid_filename",
                stage="write",
                retryable=False,
            )
        normalized = value.strip()
        if not normalized:
            raise AttachmentValidationError(
                "Payment proof filename is required.",
                category="missing_filename",
                stage="write",
                retryable=False,
            )
        # Keep only a display basename.  This is not a security boundary for
        # storage (the generated reference is), but prevents a browser path
        # from becoming persisted display metadata.
        normalized = re.split(r"[\\/]", normalized)[-1]
        if normalized in {"", ".", ".."}:
            normalized = "payment-proof"
        return normalized[:255]

    @staticmethod
    def _display_mime_type(value: Any) -> str:
        if not isinstance(value, str) or "\x00" in value:
            raise AttachmentValidationError(
                "Payment proof MIME type is invalid.",
                category="invalid_mime_type",
                stage="write",
                retryable=False,
            )
        normalized = value.strip()
        if not normalized or len(normalized) > 255:
            raise AttachmentValidationError(
                "Payment proof MIME type is invalid.",
                category="invalid_mime_type",
                stage="write",
                retryable=False,
            )
        return normalized

    @staticmethod
    def _validate_payment_id(value: Any) -> str:
        if not isinstance(value, str) or not _PAYMENT_ID_PATTERN.fullmatch(value):
            raise AttachmentSecurityError(
                "Payment proof payment identity is unsafe.",
                category="invalid_payment_id",
                stage="validation",
                retryable=False,
            )
        return value

    @staticmethod
    def _reference_payment_id(reference: str) -> str:
        if not isinstance(reference, str):
            return ""
        parts = reference.split("/")
        return parts[0] if parts else ""

    def _normalize_root(self, raw_root: Path) -> Path:
        try:
            self._assert_no_symlink_components(raw_root)
            normalized = raw_root.resolve(strict=False)
            self._assert_no_symlink_components(normalized)
            return normalized
        except AttachmentSecurityError:
            raise
        except (OSError, RuntimeError):
            raise AttachmentSecurityError(
                "Configured attachment root is unsafe.",
                category="unsafe_root",
                stage="validation",
                retryable=False,
            ) from None

    def _ensure_root(self) -> None:
        try:
            if self._root.exists() and self._root.is_symlink():
                raise AttachmentSecurityError(
                    "Configured attachment root is unsafe.",
                    category="unsafe_root",
                    stage="validation",
                    retryable=False,
                )
            self._root.mkdir(parents=True, exist_ok=True)
            self._assert_no_symlink_components(self._root)
            if not self._root.is_dir():
                raise OSError("attachment root is not a directory")
        except AttachmentSecurityError:
            raise
        except (OSError, RuntimeError):
            raise AttachmentWriteError(
                "Attachment root is unavailable.",
                category="root_unavailable",
                stage="write",
                retryable=True,
            ) from None

    def _ensure_payment_directory(self, payment_dir: Path, payment_id: str) -> None:
        try:
            self._assert_safe_internal_path(payment_dir, payment_id)
            payment_dir.mkdir(mode=0o700, exist_ok=True)
            self._assert_safe_internal_path(payment_dir, payment_id)
            if not payment_dir.is_dir():
                raise OSError("payment attachment directory is not a directory")
        except AttachmentServiceError:
            raise
        except (OSError, RuntimeError):
            raise AttachmentWriteError(
                "Payment proof directory is unavailable.",
                category="directory_unavailable",
                stage="write",
                retryable=True,
            ) from None

    def _path_for_reference(
        self,
        reference: str,
        *,
        expected_payment_id: str | None,
        must_exist: bool,
    ) -> Path:
        if not isinstance(reference, str) or not reference or "\x00" in reference:
            raise AttachmentSecurityError(
                "Payment proof reference is unsafe.",
                category="invalid_reference",
                stage="validation",
                retryable=False,
            )
        if "\\" in reference or PurePosixPath(reference).as_posix() != reference:
            raise AttachmentSecurityError(
                "Payment proof reference is not normalized.",
                category="unnormalized_reference",
                stage="validation",
                retryable=False,
            )
        posix_reference = PurePosixPath(reference)
        windows_reference = PureWindowsPath(reference)
        if posix_reference.is_absolute() or windows_reference.is_absolute() or windows_reference.drive:
            raise AttachmentSecurityError(
                "Payment proof reference cannot be absolute.",
                category="absolute_reference",
                stage="validation",
                retryable=False,
            )
        parts = posix_reference.parts
        if len(parts) != 2 or any(part in {"", ".", ".."} for part in parts):
            raise AttachmentSecurityError(
                "Payment proof reference has an invalid scope.",
                category="traversal_reference",
                stage="validation",
                retryable=False,
            )
        payment_id = self._validate_payment_id(parts[0])
        if expected_payment_id is not None and payment_id != expected_payment_id:
            raise AttachmentSecurityError(
                "Payment proof reference is assigned to another payment.",
                category="payment_mismatch",
                stage="validation",
                retryable=False,
            )
        if not _REFERENCE_TOKEN_PATTERN.fullmatch(parts[1]):
            raise AttachmentSecurityError(
                "Payment proof reference token is invalid.",
                category="invalid_reference_token",
                stage="validation",
                retryable=False,
            )

        path = self._root.joinpath(*parts)
        self._assert_safe_internal_path(path, payment_id)
        if must_exist and not path.exists():
            raise AttachmentReadbackError(
                "Payment proof is unavailable.",
                category="not_found",
                stage="readback",
                retryable=True,
            )
        return path

    def _assert_safe_internal_path(self, path: Path, payment_id: str) -> None:
        safe_payment_id = self._validate_payment_id(payment_id)
        try:
            absolute = Path(os.path.abspath(os.fspath(path)))
            relative = absolute.relative_to(self._root)
        except (ValueError, OSError, RuntimeError):
            raise AttachmentSecurityError(
                "Payment proof path is outside the managed root.",
                category="outside_root",
                stage="validation",
                retryable=False,
            ) from None
        if not relative.parts or relative.parts[0] != safe_payment_id:
            raise AttachmentSecurityError(
                "Payment proof path is assigned to another payment.",
                category="payment_mismatch",
                stage="validation",
                retryable=False,
            )
        self._assert_no_symlink_components(absolute)
        try:
            resolved = absolute.resolve(strict=False)
            resolved.relative_to(self._root)
            if resolved != absolute:
                raise AttachmentSecurityError(
                    "Payment proof path contains a symlink.",
                    category="symlink_detected",
                    stage="validation",
                    retryable=False,
                )
        except AttachmentSecurityError:
            raise
        except (ValueError, OSError, RuntimeError):
            raise AttachmentSecurityError(
                "Payment proof path is unsafe.",
                category="unsafe_path",
                stage="validation",
                retryable=False,
            ) from None

    @staticmethod
    def _assert_no_symlink_components(path: Path) -> None:
        """Reject symlink components without following them."""

        current = Path(path.anchor) if path.anchor else Path()
        for part in path.parts:
            if part == path.anchor:
                continue
            current = current / part
            try:
                if current.is_symlink():
                    raise AttachmentSecurityError(
                        "Payment proof path contains a symlink.",
                        category="symlink_detected",
                        stage="validation",
                        retryable=False,
                    )
            except AttachmentSecurityError:
                raise
            except OSError:
                raise AttachmentSecurityError(
                    "Payment proof path could not be validated.",
                    category="unsafe_path",
                    stage="validation",
                    retryable=False,
                ) from None

    def _read_safe_path(self, path: Path, payment_id: str) -> bytes:
        self._assert_safe_internal_path(path, payment_id)
        if not path.is_file() or path.is_symlink():
            raise AttachmentReadbackError(
                "Payment proof is unavailable.",
                category="not_a_file",
                stage="readback",
                retryable=True,
            )

        flags = os.O_RDONLY | getattr(os, "O_BINARY", 0) | getattr(os, "O_NOFOLLOW", 0)
        file_descriptor: int | None = None
        try:
            file_descriptor = os.open(os.fspath(path), flags)
            with os.fdopen(file_descriptor, "rb") as attachment_file:
                file_descriptor = None
                content = attachment_file.read()
            if self._max_size_bytes is not None and len(content) > self._max_size_bytes:
                raise AttachmentReadbackError(
                    "Payment proof exceeds the configured size limit.",
                    category="size_exceeded",
                    stage="readback",
                    retryable=False,
                )
            self._assert_safe_internal_path(path, payment_id)
            return content
        except AttachmentServiceError:
            raise
        except (OSError, ValueError):
            raise AttachmentReadbackError(
                "Payment proof is unavailable.",
                category="read_failed",
                stage="readback",
                retryable=True,
            ) from None
        finally:
            if file_descriptor is not None:
                try:
                    os.close(file_descriptor)
                except OSError:
                    pass

    def _assert_owned_staged_attachment(self, staged: StagedAttachment) -> None:
        if not isinstance(staged, StagedAttachment) or staged._service is not self:
            raise AttachmentSecurityError(
                "Staged payment proof does not belong to this service.",
                category="foreign_stage",
                stage="validation",
                retryable=False,
            )
        self._validate_payment_id(staged.payment_id)
        self._path_for_reference(
            staged.reference,
            expected_payment_id=staged.payment_id,
            must_exist=False,
        )

    def _unlink_staged_path(self, path: Path) -> CleanupResult:
        try:
            # Staging paths are created by this process, but still validate
            # their lexical containment and reject symlink targets.
            absolute = Path(os.path.abspath(os.fspath(path)))
            absolute.relative_to(self._root)
            self._assert_no_symlink_components(absolute)
            if not absolute.exists() and not absolute.is_symlink():
                return CleanupResult(True)
            if absolute.is_symlink() or not absolute.is_file():
                return CleanupResult(False, "unsafe_target")
            absolute.unlink()
            return CleanupResult(True)
        except AttachmentSecurityError as exc:
            return CleanupResult(False, self._safe_cleanup_category(exc.category))
        except (OSError, ValueError, RuntimeError):
            return CleanupResult(False, "unlink_failed")

    def _unlink_managed_path(self, path: Path, payment_id: str) -> CleanupResult:
        try:
            self._assert_safe_internal_path(path, payment_id)
            if not path.exists() and not path.is_symlink():
                return CleanupResult(True)
            if path.is_symlink() or not path.is_file():
                return CleanupResult(False, "unsafe_target")
            path.unlink()
            return CleanupResult(True)
        except AttachmentSecurityError as exc:
            return CleanupResult(False, self._safe_cleanup_category(exc.category))
        except (OSError, ValueError, RuntimeError):
            return CleanupResult(False, "unlink_failed")

    @staticmethod
    def _safe_cleanup_category(category: str | None) -> str:
        allowed = {
            "invalid_reference",
            "unnormalized_reference",
            "absolute_reference",
            "traversal_reference",
            "invalid_reference_token",
            "invalid_payment_id",
            "payment_mismatch",
            "outside_root",
            "symlink_detected",
            "unsafe_path",
            "unsafe_target",
            "unlink_failed",
            "foreign_stage",
        }
        return category if category in allowed else "cleanup_failed"


